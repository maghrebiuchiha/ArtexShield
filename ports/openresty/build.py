"""Write the OpenResty port's generated Lua files, or check them.

    python ports/openresty/build.py            # write
    python ports/openresty/build.py --check    # exit 1 if either is out of date

- lib/resty/artex_shield/patterns.lua: spec/patterns.json as a Lua table.
  The port translates the patterns to PCRE when it loads (signatures.lua).
- lib/resty/artex_shield/unicode.lua: what Lua lacks and the reference uses,
  taken from this Python: str.lower() and str.upper() for every non-ASCII
  character they change, and the characters whose NFKC form holds one of
  / ? # @ : (urllib.parse.urlsplit refuses a netloc that does).

The Unicode tables follow this Python's Unicode version. --check compares
them only when it is the version the file was written with, and says so
otherwise; the patterns are always compared.
"""
import json
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
LIB = os.path.join(HERE, "lib", "resty", "artex_shield")
PATTERNS = os.path.join(LIB, "patterns.lua")
UNICODE = os.path.join(LIB, "unicode.lua")


def lua_str(s: str) -> str:
    """A Lua 5.1 string literal holding s as UTF-8."""
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '"\\':
            out.append("\\" + c)
        elif 0x20 <= b < 0x7f:
            out.append(c)
        else:
            out.append("\\%d" % b)
    return '"' + "".join(out) + '"'


def lua_value(v, indent=""):
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        if all(not isinstance(x, (list, dict)) for x in v):
            return "{" + ", ".join(lua_value(x) for x in v) + "}"
        inner = indent + "  "
        return "{\n" + "".join(inner + lua_value(x, inner) + ",\n" for x in v) + indent + "}"
    if isinstance(v, dict):
        inner = indent + "  "
        return "{\n" + "".join("%s[%s] = %s,\n" % (inner, lua_str(k), lua_value(x, inner)) for k, x in v.items()) \
            + indent + "}"
    raise TypeError(type(v))


def patterns_lua() -> str:
    with open(os.path.join(ROOT, "spec", "patterns.json"), encoding="utf-8") as f:
        patterns = json.load(f)
    return ("-- Generated by ports/openresty/build.py from spec/patterns.json. Do not edit.\n"
            "return " + lua_value(patterns) + "\n")


def unicode_lua() -> str:
    def chars():
        for cp in range(0x80, sys.maxunicode + 1):
            if not 0xD800 <= cp <= 0xDFFF:
                yield cp, chr(cp)

    def table(pairs, per_line=6):
        items = ["[0x%04X] = %s" % (cp, v) for cp, v in pairs]
        lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
        return "{\n" + "".join("    " + line + ",\n" for line in lines) + "  }"

    lower = [(cp, lua_str(c.lower())) for cp, c in chars() if c.lower() != c]
    upper = [(cp, lua_str(c.upper())) for cp, c in chars() if c.upper() != c]
    nfkc = [(cp, "true") for cp, c in chars() if any(x in unicodedata.normalize("NFKC", c) for x in "/?#@:")]
    return ("-- Generated by ports/openresty/build.py from Python's own Unicode data. Do not edit.\n"
            "-- lower/upper: str.lower() and str.upper() of each non-ASCII character they change (ASCII is\n"
            "-- string.lower's). nfkc_unsafe: characters whose NFKC form holds / ? # @ or :.\n"
            "return {\n"
            "  unidata_version = %s,\n"
            "  lower = %s,\n"
            "  upper = %s,\n"
            "  nfkc_unsafe = %s,\n"
            "}\n") % (lua_str(unicodedata.unidata_version), table(lower), table(upper), table(nfkc, 8))


def written_version(path: str):
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                if "unidata_version" in line:
                    return line.split('"')[1]
    except OSError:
        pass
    return None


def main(argv) -> int:
    check = "--check" in argv
    stale = []
    outputs = [(PATTERNS, patterns_lua())]
    version = written_version(UNICODE)
    if check and version is not None and version != unicodedata.unidata_version:
        print("unicode.lua was written with Unicode %s and this Python has %s: not compared"
              % (version, unicodedata.unidata_version))
    else:
        outputs.append((UNICODE, unicode_lua()))
    for path, text in outputs:
        try:
            with open(path, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = None
        if current == text:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print("wrote", os.path.relpath(path, ROOT))
    if stale:
        print("out of date (run python ports/openresty/build.py):", ", ".join(stale))
        return 1
    if check:
        print("the generated Lua files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
