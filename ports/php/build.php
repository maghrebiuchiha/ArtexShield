<?php
/**
 * Writes artex-shield/patterns.php: patterns.json translated to PCRE once,
 * so a request loads them from OPcache instead of translating each time.
 * Run after copying a new spec/patterns.json in; tests/vectors.php fails
 * while the two disagree.
 *
 *   cp ../../spec/patterns.json artex-shield/ && php build.php
 */
declare(strict_types=1);

require __DIR__ . '/artex-shield/autoload.php';

$out = __DIR__ . '/artex-shield/patterns.php';
$code = "<?php\n// Generated by ports/php/build.php from patterns.json. Do not edit.\nreturn "
    . var_export(ArtexShield\Signatures::fromJson(), true) . ";\n";
file_put_contents($out, $code);
echo "wrote $out\n";
